#!/usr/bin/env python3
"""World coverage: which parts of the setting the Sunday Morning stories use.

Usage (from the repository root):
    python3 atlas/tools/world_coverage.py

Reads every Atlas part (atlas/<folder>/<name>.json) and every Sunday Morning
story page and draft (wiki/Sunday-Morning/Stories, wiki/Sunday-Morning/Drafts).
A thing counts as *used* by a story when the story is connected to it on the
Atlas, or when the story's page or draft links to the thing's wiki section
(or to its page, when the thing has no section).

Writes atlas/coverage/Coverage.md. It's a derived view, so don't hand-edit it.
"""
import collections, glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WIKI = os.path.join(ROOT, "wiki")
ATLAS = os.path.join(ROOT, "atlas")
OUT = os.path.join(ATLAS, "coverage", "Coverage.md")
SM = os.path.join(WIKI, "Sunday-Morning")

# Parts that aren't "world to use": rules, open questions and the story layer itself.
SKIP_PARTS = {"Foundations": "world rules: constraints every story follows, not material to use",
              "Questions": "open questions: deliberately not settled by any story"}
SKIP_KINDS = {"story", "seed", "sm", "overview"}


def story_links():
    pages, anchors = collections.defaultdict(set), collections.defaultdict(set)
    titles = {}
    for d in ("Stories", "Drafts"):
        for p in sorted(glob.glob(os.path.join(SM, d, "*.md"))):
            name = os.path.basename(p)[:-3]
            if name in ("README", "Story-Seeds"):
                continue
            text = open(p, encoding="utf-8").read()
            m = re.search(r"^#\s+(.*?)(\s+—\s+draft)?$", text, re.M)
            titles.setdefault(name, m.group(1).strip() if m else name)
            for m in re.finditer(r"\]\(([^)\s]+)\)", text):
                link = m.group(1)
                if link.startswith(("http", "mailto")):
                    continue
                f, _, a = link.partition("#")
                tgt = os.path.normpath(os.path.join(os.path.dirname(p), f)) if f else p
                rel = os.path.relpath(tgt, WIKI).replace(os.sep, "/")
                pages[rel].add(name)
                if a:
                    anchors[rel + "#" + a].add(name)
    return pages, anchors, titles


def main():
    parts = []
    for f in sorted(glob.glob(os.path.join(ATLAS, "*", "*.json"))):
        try:
            d = json.load(open(f, encoding="utf-8"))
        except (ValueError, OSError):
            continue
        if isinstance(d, dict) and "part" in d and "nodes" in d:
            parts.append(d)
    parts.sort(key=lambda d: d["part"])
    pages, anchors, titles = story_links()

    node_story = {}
    story_nodes = {}
    for d in parts:
        for n in d["nodes"]:
            if n["kind"] in ("story", "seed"):
                src = n.get("draft") or n.get("src", "")
                base = os.path.basename(src.split("#")[0])[:-3] if src else n["id"]
                story_nodes[n["id"]] = base
    used = collections.defaultdict(set)
    for d in parts:
        for e in d["edges"]:
            for a, b in ((e["from"], e["to"]), (e["to"], e["from"])):
                if a in story_nodes:
                    used[b].add(story_nodes[a])
    for d in parts:
        for n in d["nodes"]:
            src = n.get("src", "")
            page = src.split("#")[0]
            if "#" in src:
                used[n["id"]] |= anchors.get(src, set())
            else:
                used[n["id"]] |= pages.get(page, set())

    rows, totals = [], []
    for d in parts:
        if d["short"] in SKIP_PARTS:
            continue
        things = [n for n in d["nodes"] if n["kind"] not in SKIP_KINDS]
        if not things:
            continue
        hit = [n for n in things if used.get(n["id"])]
        totals.append((d["short"], d["title"], len(hit), len(things)))
        bysec = collections.OrderedDict()
        for n in things:
            bysec.setdefault(n.get("section") or "Other", []).append(n)
        rows.append((d, bysec))

    kinds = {}
    for d in parts:
        kinds.update(d.get("kinds", {}))

    out = ["# World coverage", "",
           "**Derived view, generated by `atlas/tools/world_coverage.py`. Don't edit by hand.** "
           "It shows which parts of the setting the [Sunday Morning stories](../../wiki/Sunday-Morning/README.md) use, "
           "so a new season can reach for what the world has and no story has touched yet "
           "([The Long Road](../../wiki/Sunday-Morning/Notes/The-Long-Road.md#using-the-world)). "
           "A thing counts as used when a story is connected to it on the [Atlas](../README.md), "
           "or when the story's plan or draft links to its wiki section. A story can use something without linking it "
           "(Season 1's language habits and many of its dishes are like that), so link the owner section in a story's World anchors.", "",
           "Being used isn't a target. A story uses what it needs, and some things (a map outline, an open question) "
           "shouldn't be used at all. Left out on purpose: " +
           "; ".join(f"**{k}** ({v})" for k, v in SKIP_PARTS.items()) + ".", "",
           "## Summary", "", "| Atlas part | Used by a story | Not yet |", "| --- | --- | --- |"]
    for short, title, h, t in totals:
        out.append(f"| {title} | {h} of {t} | {t - h} |")
    for d, bysec in rows:
        out += ["", f"## {d['title']}", ""]
        for sec, things in bysec.items():
            un = [n for n in things if not used.get(n["id"])]
            us = [n for n in things if used.get(n["id"])]
            out.append(f"### {sec}")
            out.append("")
            if un:
                out.append("**Not yet in any story:** " + ", ".join(
                    f"[{n['label']}](../../wiki/{n['src']})" for n in un) + ".")
                out.append("")
            if us:
                out.append("**Used:** " + "; ".join(
                    f"{n['label']} ({', '.join(sorted(titles.get(s, s) for s in used[n['id']]))})" for n in us) + ".")
                out.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(out).rstrip() + "\n")
    print("Wrote", os.path.relpath(OUT, ROOT))
    for short, title, h, t in totals:
        print(f"  {title}: {h}/{t}")


if __name__ == "__main__":
    main()
